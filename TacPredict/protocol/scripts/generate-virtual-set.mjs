/**
 * Builds the Virtual USDC contract set from the six audited-in-place contracts.
 *
 * The six production contracts pin collateral to native Base USDC, so they can never hold virtual
 * money. Instead of hand-copying them (and letting the copies drift), this script derives the virtual
 * set from the originals:
 *   - every contract is renamed with a "Virtual" prefix (Registry, Oracle, Factory, Positions, Exchange, Settlement);
 *   - the registry constructor requires a collateral token that says it is virtual instead of native USDC;
 *   - the exchange signs under its own EIP-712 domain name, so a signature for one set is never valid in the other.
 * Nothing else changes: trading, settlement, oracle and position logic are the same bytes of source.
 *
 * The originals are never edited. Run `node scripts/generate-virtual-set.mjs` to rewrite the generated files;
 * `test/virtual-set-source.test.mjs` fails if they drift from what this script would produce.
 */
import fs from "node:fs";
import path from "node:path";

export const ORIGINALS = [
  "MarketRegistry",
  "ResolutionOracle",
  "MarketFactory",
  "ConditionalPositions",
  "Exchange",
  "Settlement",
];
export const virtualName = (name) => `Virtual${name}`;

const HEADER =
  "// GENERATED by scripts/generate-virtual-set.mjs from contracts/{ORIGINAL}.sol. Do not edit by hand.\n" +
  "// Virtual USDC set: same logic as the production contract, collateral is VirtualUSDC (never real money).\n";

function once(text, from, to, label) {
  const first = text.indexOf(from);
  if (first < 0 || text.indexOf(from, first + 1) >= 0)
    throw new Error(`generate-virtual-set: expected exactly one match for ${label}`);
  return text.replace(from, () => to);
}

export function transform(name, source) {
  let text = source;
  for (const original of ORIGINALS)
    text = text.replace(new RegExp(`\\b${original}\\b`, "g"), virtualName(original));

  if (name === "MarketRegistry") {
    text = once(
      text,
      `        address nativeUSDC = block.chainid == 8453 ? 0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913 : 0x036CbD53842c5426634e7929541eC2318f3dCF7e;\n        require(usdc == nativeUSDC, "Native Base USDC only");\n`,
      "",
      "registry native USDC pin",
    );
    text = once(
      text,
      `        require(IERC20Metadata(usdc).decimals() == 6, "USDC decimals");\n`,
      `        require(IERC20Metadata(usdc).decimals() == 6, "USDC decimals");\n        require(IVirtualCollateral(usdc).isVirtualCollateral(), "Virtual USDC only");\n`,
      "registry decimals check",
    );
    text = once(
      text,
      `/// @notice Immutable market terms.`,
      `/// @dev Marker implemented only by VirtualUSDC. Real USDC or any other token fails this check.\ninterface IVirtualCollateral { function isVirtualCollateral() external view returns (bool); }\n\n/// @notice Immutable market terms.`,
      "registry notice",
    );
  }
  if (name === "Exchange")
    text = once(text, `EIP712("TacPredictExchange", "1")`, `EIP712("TacPredictVirtualExchange", "1")`, "exchange domain");

  const [license, ...rest] = text.split("\n");
  if (!license.startsWith("// SPDX-License-Identifier"))
    throw new Error(`generate-virtual-set: ${name} has no SPDX line`);
  return `${license}\n${HEADER.replace("{ORIGINAL}", name)}${rest.join("\n")}`;
}

export function generate(contractsDir = path.resolve(import.meta.dirname, "../contracts")) {
  return Object.fromEntries(
    ORIGINALS.map((name) => [
      `${virtualName(name)}.sol`,
      transform(name, fs.readFileSync(path.join(contractsDir, `${name}.sol`), "utf8")),
    ]),
  );
}

if (process.argv[1] === import.meta.filename) {
  const dir = path.resolve(import.meta.dirname, "../contracts");
  for (const [file, content] of Object.entries(generate(dir))) {
    fs.writeFileSync(path.join(dir, file), content);
    console.log("wrote contracts/" + file);
  }
}
